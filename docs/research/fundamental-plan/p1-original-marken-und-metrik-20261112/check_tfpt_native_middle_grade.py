"""Test the colour-centre grading on the unchanged native Q assembler."""
from pathlib import Path
import sys
import numpy as np

repo = Path(sys.argv[1]).resolve()
q = repo / "experiments/theory-contracts/original-paper-source-reconciliation-20261102/contribution_20261106Q"
original_comparator = repo / "experiments/theory-contracts/chat-triangulation-20261108"
for folder in (q/"runtime", repo/"verification", original_comparator):
    sys.path.insert(0, str(folder))
from assemble import Assembler
from check_mixed_higgs_eich import gauge_operators

a = Assembler(q/"domain/native-diagnostic-v1.json")
native = a.assemble({"genes":[2,2,2]})
weak, Y = gauge_operators()
assert np.array_equal(Y,np.diag(Y.diagonal()))
integer_charge = np.rint(6*Y.diagonal().real).astype(int)
assert np.max(np.abs(6*Y.diagonal()-integer_charge))<1e-13
grade = integer_charge%3
different = grade[:,None] != grade[None,:]
fourier_grade = np.tile(grade,len(native["modes"]))
cross_fourier = fourier_grade[:,None] != fourier_grade[None,:]
tested = [("gamma96",a.gamma),("Majorana",a.DM),*[(f"Higgs direction {j}",m) for j,m in enumerate(a.V)],*[(f"weak {j}",m) for j,m in enumerate(weak)],("hypercharge",Y)]
for name,m in tested:
    assert np.count_nonzero(m[different])==0, name
assert np.count_nonzero(native["h_N"][cross_fourier])==0
# Marked E8 root gamma has hypercharge -1/3, colour triality 1. Its
# matrix elements would be outside the conserved native blocks above.
assert (-2)%3==1 and 2%3==2
print('Q domain',native['native_inputs_sha256'])
print('96 native colour-centre multiplicities:', np.bincount(grade).tolist())
print('Exact zero off the colour-centre blocks on all',len(tested),'generators and on the native 384 operator.')
print('Marked E8 ends have grades 0 and 2; the actual middle current has grade 1, so it is absent from the algebra generated by these native neutral matrices.')
