"""Marked torus Hodge readout and mirror obstruction, exact symbolic controls."""
from itertools import product
import sympy as sp

A = sp.Matrix([[1, 1], [0, 1]])
B = sp.Matrix([[1, 0], [-1, 1]])
I = sp.eye(2)
LETTERS = {'a': A, 'b': B, 'A': A.inv(), 'B': B.inv()}
x = sp.symbols('x', real=True)
y = sp.symbols('y', positive=True)
z = x + sp.I*y
radius2 = x*x+y*y


def transport(word):
    M = I
    for letter in word:
        M = M * LETTERS[letter]
    return M


def excess(M):
    """sinh²(d_H(z,Mz)/2) in the upper half plane, marked standard Möbius action."""
    a,b,c,d = list(M)
    p = c*z*z+(d-a)*z-b
    return sp.expand(p*p.conjugate()).simplify()/(4*y**2)


def overlap(M):
    return 1/sp.sqrt(1+excess(M))


def eq(lhs,rhs):
    assert sp.factor(lhs-rhs)==0,(lhs,rhs)


def main():
    # Normalized Gaussian overlap on area-one metrics; invariant under a common
    # det-one congruence, with no cycle vector or coordinate projection chosen.
    G = sp.Matrix([[1,x],[x,radius2]])/y
    eq(G.det(),1)
    g = sp.Matrix(sp.symbols('h:4')).reshape(2,2)
    T = sp.Matrix([[0,-1],[1,0]])
    for M in (A,B,T,A**2*B**-2):
        # For this plus-x convention, the Möbius action is a congruence by
        # [[d,b],[c,a]] (a,b,c,d are the rows of M).
        a,b,c,d = list(M)
        U = sp.Matrix([[d,b],[c,a]])
        H = U.T*G*U
        eq(H.det(),1)
        eq(((G+H)/2).det(),1+excess(M))
        eq(((g.T*(G+H)*g)/2).det(),g.det()**2*((G+H)/2).det())

    E2=excess(A**2)+excess(B**2)
    eq(E2-2,(x*x*(x*x+2*y*y)+(y*y-1)**2)/y**2)
    # Product fidelity bound follows p,q>=0, pq>=1, (1+p)(1+q)>=4.
    eq(excess(A**2)*excess(B**2),radius2**2/y**4)
    third=A*B*A.inv()
    E3=E2+excess(third**2)
    v=sp.symbols('v',real=True)
    eq(E3.subs(x,v+sp.Rational(1,2))-4,
       (2*v**4+(4*y*y+3)*v*v+2*(y*y-sp.Rational(3,4))**2)/y**2)
    print('two given double exchanges: unique minimum E(i) =',E2.subs({x:0,y:1}))
    print('with third symmetric slope: unique hexagonal minimum E =',
          sp.simplify(E3.subs({x:sp.Rational(1,2),y:sp.sqrt(3)/2})))

    candidates=[]
    for word in product(LETTERS,repeat=4):
        if any(s==t.swapcase() for s,t in zip(word,word[1:])):
            continue
        if sum(1 if c.islower() else -1 for c in word)!=0:
            continue
        M=transport(word)
        if M!=I and all(int(v)%2==0 for v in M-I):
            candidates.append(M)
    assert len(candidates)==8
    total=4*sum(excess(M) for M in candidates)
    eq(total-272,8*(7*(radius2-1)**2+10*x*x)/y**2)
    print('eight shortest hidden transports: unique minimum sum 4e =',
          total.subs({x:0,y:1}))
    print('Gaussian amplitudes of eight hidden histories at square:',
          sorted(str(overlap(M).subs({x:0,y:1})) for M in candidates))

    # Axis of one example. 4e -(tr²-4) is a perfect square in general.
    a,b,c,d = sp.symbols('a b c d',real=True)
    p=c*z*z+(d-a)*z-b
    axis=c*radius2+(d-a)*x-b
    eq((p*p.conjugate()).expand()-y*y*((a+d)**2-4*(a*d-b*c)),axis**2)
    H=A**2*B**-2
    print('one hyperbolic history, trace',H.trace(),'; max amplitude 2/trace =',
          sp.Rational(2,H.trace()),'; axis (x-1)^2+y^2=2')

    # Positive representative v for projective inverse. Reflection theta acts
    # individually on generators, while group inverse also reverses word order.
    u,vw='a','babab'
    mirror=lambda word: ''.join(c.swapcase() for c in word)
    assert transport(u)*transport(vw)==-I and transport(mirror(vw))==-A
    M=[[transport(mirror(s)).inv()*transport(t) for t in (u,vw)] for s in (u,vw)]
    assert M==[[A**2,-I],[-I,A**-2]]
    p=overlap(A**2).simplify()
    eq(p**2,y**2/(1+y**2))
    eq(overlap(A**-2),p)
    eq(overlap(-I),1)
    det=sp.factor(p**2-1)
    print('mirror Gaussian Gram diagonal p =',p,'; off diagonal 1; det =',det)
    print('square and hex determinants:',det.subs(y,1),det.subs(y,sp.sqrt(3)/2))

    # Finite check of subgroup-indicator formula on all positive words up
    # to length 5 individually. Identity of a subgroup power is recognized
    # by its full torus image and abelianization; for these comparisons the
    # unique pair of these invariants separates all B3 central lifts since
    # the kernel B3 -> SL2Z is generated by (ab)^6.
    def subgroup_phi_positive(word):
        M=transport(word)
        n=len(word)
        return (int(M==A**n)+int(M==B**n))*sp.S.Half
    positive=[''.join(w) for k in range(6) for w in product('ab',repeat=k)]
    for s,t in product(positive,repeat=2):
        real=subgroup_phi_positive(s[::-1]+t)
        predicted=sum((set(s+t)<=set(c)) for c in 'ab')*sp.S.Half
        assert real==predicted
    R=sp.Matrix([[subgroup_phi_positive(s[::-1]+t) for t in ('aa','bb')]
                 for s in ('aa','bb')])
    print('parabolic subgroup kernel: reflected aa/bb Gram',R.tolist(),
          '; values aaaa, aabb:',subgroup_phi_positive('aaaa'),subgroup_phi_positive('aabb'))
    print('finite positive-word pairs checked:',len(positive)**2)


if __name__=='__main__':
    main()
