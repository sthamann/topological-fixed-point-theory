def purity_sum(v):
    s = (v[:16] + 1j * v[16:]) / np.linalg.norm(v[:16] + 1j * v[16:])
    return sum(np.trace(np.linalg.matrix_power(reduced(s, k, 4), 2)).real for k in ((0, 1), (0, 2), (0, 3)))


