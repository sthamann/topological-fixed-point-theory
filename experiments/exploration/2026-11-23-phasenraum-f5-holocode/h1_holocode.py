# ---------------------------------------------------------------- 5. triangle group quotients


def order(perm):
    return perm.order()


def compose(p, q):
    """(p*q)(x) = q(p(x)), the sympy convention."""
    return tuple(q[i] for i in p)


def perm_order(p):
    x, k, e = p, 1, tuple(range(len(p)))
    while x != e:
        x, k = compose(x, p), k + 1
    return k


def closure_size(gens, cap):
    seen = {tuple(range(len(gens[0])))}
    frontier = list(seen)
    while frontier:
        nxt = []
        for g in frontier:
            for h in gens:
                m = compose(g, h)
                if m not in seen:
                    seen.add(m)
                    nxt.append(m)
                    if len(seen) > cap:
                        return None
        frontier = nxt
    return len(seen)


def transitive(gens, n):
    orbit, stack = {0}, [0]
    while stack:
        x = stack.pop()
        for g in gens:
            y = g[x]
            if y not in orbit:
                orbit.add(y)
                stack.append(y)
    return len(orbit) == n


def smallest_quotient(sig, max_degree=8, cap=5000, samples=20000):
    """Smallest group generated by a, b with orders (ord a, ord b, ord ab) exactly sig among
    transitive permutation groups of degree <= max_degree: exhaustive up to degree 6,
    random pairs for degrees 7 and 8. A lower bound on minimality only within this search."""
    l, m, n = sig
    best = None
    for deg in range(2, max_degree + 1):
        if deg <= 6:
            perms = list(itertools.permutations(range(deg)))
            A = [x for x in perms if perm_order(x) == l]
            B = [x for x in perms if perm_order(x) == m]
            pairs = ((a, b) for a in A for b in B)
        else:
            def draw(k):
                while True:
                    x = tuple(int(v) for v in rng.permutation(deg))
                    if perm_order(x) == k:
                        return x
            pairs = ((draw(l), draw(m)) for _ in range(samples))
        for a, b in pairs:
            if perm_order(compose(a, b)) != n or not transitive((a, b), deg):
                continue
            o = closure_size((a, b), cap if best is None else best - 1)
            if o is not None and (best is None or o < best):
                best, where = o, deg
    return (best, where) if best else (None, None)


print("5. Kleinste glatte endliche Bilder (transitive Darstellungen bis Grad 8):")
