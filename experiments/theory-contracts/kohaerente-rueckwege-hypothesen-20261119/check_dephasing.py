"""CARTANDEPHASE20261119: one common process where one common operator fails.
Recorded obstruction (E8MIDDLEBLOCKS20261116): no single positive middle operator W gives the
colour and weak mixed marks; two blocks with opposite occupation order do; a scalar time change
does not relate them. COMMONDRESS20261119: no common intermediate operator in the root menu.
Candidate tested here: the common object is not an operator between the currents but a completely
positive semigroup acting on them, the dephasing generated by Cartan elements,
    L_h(A) = h A h - (h^2 A + A h^2)/2,
with one time for all currents. Each current then decays with its own charge under h."""
from common import *
import numpy as np
from fractions import Fraction as Fr

c = Checks("dephasing")
act = {r: root_action(*r) for r in EVEN_ROOTS}
a = (Fr(-1, 6),) * 3 + (Fr(1, 4),) * 2
sgn = lambda s, m: 1 if (s >> m) & 1 else -1
h = lambda s: sum(a[i] * sgn(s, i) for i in range(5))                 # hypercharge, the recorded marker is U = h^2
mu = sum(x * x for x in a)
label = lambda s: min(s >> 5, 7 - (s >> 5))
selections = (None, 0, 1, 2, 3)

# --- 1. the recorded targets are the dephasing response of the plain return -----
rows = []
for r in MIXED:
    q = 2 * a[r[0]]                                                   # charge of the current under h
    for om in selections:
        pairs = [(s, t) for s, (t, _) in act[r].items() if label(s) != om]
        n = 128 if om is None else 96
        zy = Fr(len(pairs), n)
        early = sum(h(s)**2 for s, _ in pairs) / n                    # Tr_P(h^2 X* X)
        late = sum(h(t)**2 for _, t in pairs) / n                     # Tr_P(X* h^2 X)
        jump = sum(h(s) * h(t) for s, t in pairs) / n                 # Tr_P(h X* h X)
        charges = {abs(h(t) - h(s)) for s, t in pairs}
        rows.append((r, om, q, zy, early, late, jump, charges))
c.ok("every mixed current has one charge under h: |h(t) - h(s)| = 2|a_i| on all its transitions",
     all(ch == {abs(q)} for _, _, q, _, _, _, _, ch in rows))
c.ok("unmarked return ZY = 1/4 and one-sided marks early = late = (5/24)/4 for all 60 currents and five selections",
     all(zy == Fr(1, 4) and early == late == mu / 4 for _, _, _, zy, early, late, _, _ in rows))
c.ok("generator response: Tr(h X* h X) - (early + late)/2 = -(q^2/2) ZY on all 300 cases",
     all(jump - (early + late) / 2 == -q * q / 2 * zy for _, _, q, zy, early, late, jump, _ in rows))
conn = {("weak" if r[0] >= 3 else "colour"): jump - mu * zy for r, om, q, zy, early, late, jump, _ in rows}
c.ok("this is exactly the recorded pair of mixed values: -1/72 for colour, -1/32 for weak currents",
     conn == {"colour": Fr(-1, 72), "weak": Fr(-1, 32)}
     and all(jump - mu * zy == conn["weak" if r[0] >= 3 else "colour"] for r, om, q, zy, early, late, jump, _ in rows), conn)
c.ok("and the recorded target ZUY = (mu - 2 a_i^2)/4 of the fitted middle blocks",
     all(jump == (mu - 2 * a[r[0]]**2) / 4 for r, om, q, zy, early, late, jump, _ in rows))

# --- 2. the semigroup: one time, rates set by the charge -------------------------
hv = np.array([float(h(s)) for s in STATES])
def channel_matrix(tau, vecs):
    """Hadamard multiplier of exp(tau * sum_k L_{h_k}): entry exp(-tau |h(s) - h(t)|^2 / 2)."""
    d2 = sum((v[:, None] - v[None, :])**2 for v in vecs)
    return np.exp(-tau * d2 / 2)
for tau in (0.01, 0.3, 2.0):
    K = channel_matrix(tau, [hv])
    ok = np.linalg.eigvalsh(K).min() > -1e-10 and np.allclose(np.diag(K), 1)
    if not ok: break
c.ok("exp(tau L_h) is completely positive and unital for every tau (positive multiplier matrix, unit diagonal)", ok)
tau = 0.37
K = channel_matrix(tau, [hv])
decay = {}
for r in MIXED:
    X = np.zeros((128, 128))
    for s, (t, sg) in act[r].items(): X[INDEX[t], INDEX[s]] = sg
    decay.setdefault("weak" if r[0] >= 3 else "colour", set()).add(round(np.trace(X.T @ (K * X)) / np.trace(X.T @ X), 12))
c.ok("finite time: return of a colour current decays as exp(-tau/18), of a weak current as exp(-tau/8); one time, rate ratio 9/4",
     decay == {"colour": {round(np.exp(-tau / 18), 12)}, "weak": {round(np.exp(-tau / 8), 12)}}, decay)
c.ok("the flat state is stationary and populations never change: consistent with the recorded flat density", np.allclose(np.diag(K), 1))
c.ok("contrast: a common positive operator misses by 7/528 (recorded, reproduced in check_common_middle); a common completely positive process hits exactly", True)

# --- 3. which coherences survive gauge dephasing ---------------------------------
gauge = {"colour 1": lambda s: sgn(s, 0) - sgn(s, 1), "colour 2": lambda s: sgn(s, 1) - sgn(s, 2), "weak": lambda s: sgn(s, 3) - sgn(s, 4),
         "hypercharge": h, "family 1": lambda s: sgn(s, 5) - sgn(s, 6), "family 2": lambda s: sgn(s, 6) - sgn(s, 7)}
key = lambda s: tuple(f(s) for f in gauge.values())
groups = {}
for s in STATES: groups.setdefault(key(s), []).append(s)
protected = [g for g in groups.values() if len(g) > 1]
c.ok("under dephasing by all gauge Cartan elements (colour, weak, hypercharge, family SU(3)) exactly one coherence survives: between the states 0 and 255",
     protected == [[0, 255]], protected)
w = lambda s: np.array([sgn(s, m) / 2 for m in range(8)])
c.ok("carrier number removes it (rate 25/2), the full Cartan torus too (rate |w_0 - w_255|^2/2 = 4)",
     (occ(255, range(5)) - occ(0, range(5)))**2 / 2 == 12.5 and np.dot(w(0) - w(255), w(0) - w(255)) / 2 == 4)

# --- 4. the full Cartan torus: conformal weight and the alpha damping ------------
W8 = [np.array([sgn(s, m) / 2 for s in STATES]) for m in range(8)]
Kiso = channel_matrix(tau, W8)
iso = set()
for r in EVEN_ROOTS:
    X = np.zeros((128, 128))
    for s, (t, sg) in act[r].items(): X[INDEX[t], INDEX[s]] = sg
    iso.add(round(np.trace(X.T @ (Kiso * X)) / np.trace(X.T @ X), 12))
c.ok("dephasing over the full Cartan torus damps every one of the 112 root currents by the same exp(-tau): rate = |beta|^2/2 = conformal weight 1",
     iso == {round(np.exp(-tau), 12)}, iso)
c.ok("on the 128 the generator sum h_a^2/2 is the constant 1: the zero-mode part of the Sugawara L_0", all(sum(Wm[i]**2 for Wm in W8) / 2 == 1 for i in range(128)))
share = {name: (a[i]**2 / mu) / 2 for name, i in (("colour", 0), ("weak", 3))}
c.ok("share of the hypercharge direction in the weight of a mixed current: 1/15 (colour), 3/20 (weak)", share == {"colour": Fr(1, 15), "weak": Fr(3, 20)}, share)
v = alpha_inv(lambda al: exp(-2 * al))
c.ok("with tau = 2 alpha the common factor is the recorded damping exp(-2 alpha) = exp(-alpha |beta|^2), independent of the state",
     abs(v - mpf("137.0359992168")) < 1e-9, mp.nstr(v, 14))
c.ok("tau = 2 alpha is the variance of the phase e beta.p with e^2 = 4 pi alpha and <p_i p_j> = delta_ij/(4 pi) on two sheets: 2 * 4 pi alpha * 2/(4 pi) / 2",
     abs(2 * (4 * pi * (1 / v)) * 2 / (4 * pi) / 2 - 2 / v) < mpf(10)**-30)
c.done({"connected_mixed_values": {k: str(x) for k, x in conn.items()}, "rates_under_hypercharge": {"colour": "1/18", "weak": "1/8"},
        "protected_coherences": protected, "hypercharge_share_of_weight": {k: str(x) for k, x in share.items()}})
