def omega_pair(m):
    ph, s = m
    n = 0
    t = s
    while t:
        low = t & -t; j = low.bit_length() - 1
        if j % 2 == 1 or not (s >> (j + 1)) & 1:      # pairs (4s,4s+1), (4s+2,4s+3) = adjacent (even, odd)
            return 0
        n += 1
        t ^= low | (low << 1)
    return ph * (-1j) ** n


