#!/usr/bin/env python3
"""Step 2 (KERNSIX20261120): dictionary from the kernel operators to the marks of the E8 word.

A  the hypercharge of the original is an affine function of the carrier polarisation; it is the
   marker of the recorded word
B  the kernel algebra generated by the normal grading G and the polarisation iota_C is a single
   copy of the 2 x 2 matrices; a 3 + 2 split cannot live in it
C  Fock space: the kernel state is flat on one normal half; a hop between the two halves acts on it
   like a current inside one half and has weight 1/4
D  eight zero modes: flat state plus the original hypercharge reproduce the recorded numbers
E  the literal reading (carrier modes are eigenmodes of iota_C, filled by the kernel state) gives a
   sharp charge and contradicts the record
"""
import itertools
from fractions import Fraction as Fr
import numpy as np
from common import Checks, grading, randc, fock, slater

c = Checks("2_dictionary")
rng = np.random.default_rng(2026112002)

# ---------------------------------------------------------------- A
eps = np.array([-1, -1, -1, 1, 1])
Y = [Fr(1, 12) + Fr(5, 12) * int(e) for e in eps]
X6 = [6 * y for y in Y]
c.ok("A1 original: Y = 1/12 + (5/12) eps_car = diag(-1/3,-1/3,-1/3,1/2,1/2), trace zero",
     Y == [Fr(-1, 3)] * 3 + [Fr(1, 2)] * 2 and sum(Y) == 0)
c.ok("A2 6 Y = (-2,-2,-2,3,3) is the marker vector of the recorded word (contract E8WORD20261116)", X6 == [-2, -2, -2, 3, 3])
c.ok("A3 trace zero and the split 3 + 2 fix the affine map up to one scale: a + b eps with 3(a-b) + 2(a+b) = 0 gives a = b/5",
     Fr(1, 12) == Fr(5, 12) / 5)

# ---------------------------------------------------------------- B
m = 5
U, _ = np.linalg.qr(randc(rng, m, m))
Z = np.zeros((m, m), complex)
G = grading(m)
iota = np.block([[Z, U.conj().T], [U, Z]])
n2 = 2 * m
I = np.eye(n2)
rows = np.vstack([np.kron(A, I) - np.kron(I, A.T) for A in (G, iota)])   # [A, X] = 0 as a linear system for vec(X)
comm_dim = n2 * n2 - np.linalg.matrix_rank(rows, tol=1e-9)
c.ok("B1 the commutant of {G, iota_C} has dimension m^2: the kernel algebra is one copy of the 2 x 2 matrices",
     comm_dim == m * m, comm_dim)
c.ok("B2 iota_C compressed to one normal half vanishes: no eigenvector of iota_C lies in a half",
     np.allclose(iota[:m, :m], 0) and np.allclose(iota[m:, m:], 0))
ok = True
for k in range(1, m + 1):
    W, _ = np.linalg.qr(randc(rng, m, k))
    V = np.block([[W, np.zeros((m, k))], [np.zeros((m, k)), U @ W]])     # invariant under G and iota_C
    P = V @ V.conj().T
    ok &= np.allclose(G @ P, P @ G) and np.allclose(iota @ P, P @ iota) and abs(np.trace(P @ iota)) < 1e-9
c.ok("B3 on every block invariant under G and iota_C the polarisation has trace zero: signature (3,2) is impossible there", ok)

# ---------------------------------------------------------------- C
m3 = 3
U3, _ = np.linalg.qr(randc(rng, m3, m3))
ann = fock(2 * m3)
graph = np.vstack([np.eye(m3), U3]) / np.sqrt(2)                          # range of P_C = (1/2)[[1,U*],[U,1]]
Om = slater(graph, ann)
half = ann[:m3]
ok = True
for _ in range(40):
    A = np.eye(2 ** (2 * m3), dtype=complex)
    for _ in range(rng.integers(1, 6)):
        a = half[rng.integers(m3)]
        A = A @ (a if rng.integers(2) else a.conj().T)
    ok &= abs(Om.conj() @ A @ Om - np.trace(A) / A.shape[0]) < 1e-12
c.ok("C1 the Fock state of P_C restricted to the modes of one normal half is the normalised trace (flat)", ok)
b = [sum(U3[k, j].conj() * ann[m3 + k] for k in range(m3)) for j in range(m3)]   # annihilator of the mode U e_j
vals, same = set(), True
for i in range(m3):
    for j in range(m3):
        if i == j:
            continue
        hop = half[i].conj().T @ b[j]
        v = hop @ Om
        vals.add(round(float(np.vdot(v, v).real), 12))
        w = half[i].conj().T @ half[j] @ Om
        same &= min(np.linalg.norm(v - s * w) for s in (1, -1)) < 1e-12
c.ok("C2 a hop from the mode U e_j of the other half to the mode e_i has weight 1/4 in the kernel state", vals == {0.25}, vals)
c.ok("C3 on the kernel state that hop equals, up to a sign, the current a_i^+ a_j inside one half", same)

# ---------------------------------------------------------------- D
N = 8
dim = 2 ** N
bits = np.array(list(itertools.product((0, 1), repeat=N)))
annz = []
for i in range(N):
    a = np.zeros((dim, dim), dtype=np.int64)
    for k, bb in enumerate(bits):
        if bb[i]:
            cc = bb.copy(); cc[i] = 0
            a[int("".join(map(str, cc)), 2), k] = (-1) ** int(bb[:i].sum())
    annz.append(a)
spin2 = 2 * bits - 1
matter = np.array([list(s).count(-1) % 2 == 0 for s in spin2])
h6 = np.array([int(x) for x in X6] + [0, 0, 0])
t6 = np.array([0, 0, 0, 3, -3, 0, 0, 0])
def marker(v):
    return np.diag(spin2 @ v)
def cur(i, si, j, sj):
    return (annz[i].T if si > 0 else annz[i]) @ (annz[j].T if sj > 0 else annz[j])
def marks(keep, Xc, v, comp=False):
    Pk = np.diag(keep.astype(np.int64)); mid = Pk if comp else np.eye(dim, dtype=np.int64)
    H = marker(v); z0 = int(np.trace(Pk))
    return (Fr(int(np.trace(Pk @ Xc.T @ mid @ Xc)), z0), Fr(int(np.trace(Pk @ H @ H)), 144 * z0),
            Fr(int(np.trace(Pk @ H @ Xc.T @ mid @ H @ Xc)), 144 * z0))
currents = [(i, si, j, sj) for i in range(5) for j in range(5, 8) for si in (1, -1) for sj in (1, -1)]
full = {k: marks(matter, cur(*k), h6) for k in currents}
trY2 = sum(y * y for y in Y)
c.ok("D1 flat state on the even half (128 states): marker weight = tr_E(Y^2)/4 = 5/24 with the hypercharge of the original",
     {v[1] for v in full.values()} == {trY2 / 4} == {Fr(5, 24)})
c.ok("D2 every one of the 60 currents between a carrier mode and a family mode has weight 1/4, as in C2",
     {v[0] for v in full.values()} == {Fr(1, 4)})
c.ok("D3 isospin marker 1/8, so hypercharge to isospin = 5/3 without any chosen scale besides the mode spin 1/2",
     marks(matter, cur(*currents[0]), t6)[1] == Fr(1, 8) and Fr(5, 24) / Fr(1, 8) == Fr(5, 3))
conn = sorted({v[2] - v[1] * v[0] for v in full.values()})
c.ok("D4 connected mixed weights -1/32 (weak) and -1/72 (colour), as recorded", conn == [Fr(-1, 32), Fr(-1, 72)], conn)
fam = [tuple(s[5:]) for s in spin2]
w = (1, 1, 1); wn = (-1, -1, -1)
keep = matter & np.array([f not in (w, wn) for f in fam])
comp = {marks(keep, cur(*k), h6, comp=True)[0] for k in currents}
c.ok("D5 three families (96 states), compressed: current weight 1/6 appears, as recorded", int(keep.sum()) == 96 and Fr(1, 6) in comp, sorted(comp))

# ---------------------------------------------------------------- E
s_pure = np.array([-1, -1, -1, 1, 1]) * Fr(1, 2)                      # E_+ filled, E_- empty
q = sum(y * s for y, s in zip(Y, s_pure))
c.ok("E1 literal reading: carrier modes filled along eps_car give the sharp charge 1, weight 1 and no spread; the record has 5/24",
     q == 1 and q * q != Fr(5, 24), (q, q * q))
c.ok("E2 hence in the dictionary eps_car acts on the modes of one normal half and commutes with the kernel algebra (B1); "
     "it is supplied by the carrier step, not by G and iota_C", comm_dim == m * m and ok)

c.done({"hypercharge": [str(y) for y in Y], "commutant_dim": int(comm_dim)})
