def spectral_moments(eps, beta=2.0):
    H0, Hint, F, h0 = model(eps)
    H = H0 + Hint
    E, V = np.linalg.eigh(H); E = E - E.min(); w8 = np.exp(-beta * E); Z = w8.sum()
    v = Q[:, 1]; psi = V.conj().T @ mode_op(v) @ V; e_v = e0[1]
    dE = E[None, :] - E[:, None]                                       # <m|psi|n>: frequency E_n - E_m
    A_w = (w8[:, None] + w8[None, :]) * np.abs(psi) ** 2 / Z          # spectral weights at w = E_n - E_m
    m0 = A_w.sum(); mu2_spec = (A_w * (dE - e_v) ** 2).sum()
    comm = mode_op(v) @ H - H @ mode_op(v) - e_v * mode_op(v)          # = f X_v
    rho_th = (V * (w8 / Z)) @ V.conj().T
    mu2_op = np.trace(rho_th @ (comm @ comm.conj().T + comm.conj().T @ comm)).real
    return m0, mu2_spec, mu2_op
