def spin_rot(Rm):
    q0 = np.sqrt(max(0.0, 1 + np.trace(Rm))) / 2
    q = np.array([Rm[2, 1] - Rm[1, 2], Rm[0, 2] - Rm[2, 0], Rm[1, 0] - Rm[0, 1]]) / (4 * q0)
