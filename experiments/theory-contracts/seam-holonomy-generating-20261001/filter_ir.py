Zp = np.diag([1.0, -1.0]); I2 = np.eye(2); low = np.array([[0, 1], [0, 0]], complex)
def fock_ops(n):
    out = []
    for i in range(n):
        m = np.eye(1, dtype=complex)
        for j in range(n):
            m = np.kron(m, Zp if j < i else (low if j == i else I2))
        out.append(m)
    return out
