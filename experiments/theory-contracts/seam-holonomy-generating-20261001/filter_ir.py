Q, _ = np.linalg.qr(rng.normal(size=(n, n)))                          # orthonormal eigenbasis of F (real)
Mr = rng.normal(size=(n, n)) + 1j * rng.normal(size=(n, n)); Mr = Mr - Mr.T
e0 = np.array([0.31, -0.42, 0.55, -0.23, 0.68, -0.6])                 # single-particle energies, diagonal in the F basis


def model(eps, g=0.7):
    fvals = np.array([0.0, eps, 1.0, 0.8, 1.2, 0.9])
    F = Q @ np.diag(fvals) @ Q.T
    h0 = Q @ np.diag(e0) @ Q.T
    rho = [sum(F[i, j] * c[j] for j in range(n)) for i in range(n)]
    Pp = sum(Mr[i, j] * rho[i] @ rho[j] for i in range(n) for j in range(n))
    O = Pp + Pp.conj().T
    Hint = -g * O @ O
    H0 = sum(h0[i, j] * c[i].conj().T @ c[j] for i in range(n) for j in range(n))
    return H0, Hint, F, h0
def mode_op(v):
    return sum(v[j].conj() * c[j] for j in range(n))                    # psi_v = v^dag psi
