def nambu_sigma(eps, beta=2.0, wn=(np.pi / 2,)):
    H0, Hint, F, h0 = model(eps)
    H = H0 + Hint
    E, V = np.linalg.eigh(H)
    E = E - E.min()
    wts = np.exp(-beta * E); Z = wts.sum()
    ops = [mode_op(Q[:, k]) for k in range(n)]                           # work in the F eigenbasis
    Nb = ops + [o.conj().T for o in ops]
    Nb_e = [V.conj().T @ o @ V for o in Nb]
    out = []
    for w_ in wn:
        z = 1j * w_
        G = np.zeros((2 * n, 2 * n), complex)
        denom = z - (E[None, :] - E[:, None])                              # (m, n): z - (E_n - E_m)
        for a in range(2 * n):
            for b in range(2 * n):
                A = Nb_e[a]; Bd = Nb_e[b].conj().T
                # G_ab(z) = (1/Z) sum_{m,n} (e^{-beta E_m} + e^{-beta E_n}) <m|A|n><n|B^dag|m> / (z - (E_n - E_m))
                G[a, b] = np.sum((wts[:, None] + wts[None, :]) * A * Bd.T / denom) / Z
        hq = np.diag(e0)
        G0inv = z * np.eye(2 * n) - np.block([[hq, np.zeros((n, n))], [np.zeros((n, n)), -hq.T]])
        out.append(G0inv - np.linalg.inv(G))
    return out
