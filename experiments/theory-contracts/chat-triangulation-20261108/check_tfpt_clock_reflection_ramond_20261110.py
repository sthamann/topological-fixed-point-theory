"""Exact comparison of the native clock, its glue reflection and five Ramond packets."""

import ast
from collections import Counter
from itertools import combinations, product
import json
from pathlib import Path
import runpy
import sys

import sympy as sp


repo = Path(sys.argv[1]).resolve()
contract = repo / "experiments/theory-contracts/chat-triangulation-20261108"
parent = runpy.run_path(str(contract / "check_ramond_full_return_20261110.py"))
cl, m, Q = (parent[k] for k in ("cl", "m", "Q"))
M, q, V = (parent[k] for k in ("M", "q", "V"))
syntax = ast.parse((repo/"verification/v634_st31_structure.py").read_text())
idx = next(ast.literal_eval(node.value) for node in syntax.body if isinstance(node, ast.Assign)
           and any(isinstance(t, ast.Name) and t.id=="SIGMA_IDX" for t in node.targets))
sigma = sp.eye(8)[idx,:]
I = sp.eye(8)
assert sigma**3 == I and sigma != I
roots = []
for i,j in combinations(range(8),2):
    for a,b in product((-1,1),repeat=2):
        root = sp.zeros(8,1)
        root[i],root[j] = a,b
        roots.append(root)
roots += [sp.Matrix(signs)/2 for signs in product((-1,1),repeat=8) if signs.count(-1)%2==0]
assert len(roots)==240
keys = {tuple(x) for x in roots}
weight = sp.Matrix([1]*5+[0]*3)
hyper = sp.Matrix([-2,-2,-2,3,3,0,0,0])/6


def glue(r):
    return int(2*weight.dot(r))%4


def differences(op):
    assert all(tuple(op*r) in keys for r in roots)
    return [int((glue(op*r)-glue(r))%4) for r in roots]


signature = differences(sigma)
powers = [sum(v!=0 for v in differences(sigma**k)) for k in range(1,4)]
j = sp.diag(*([sp.Matrix([[0,-1],[1,0]])]*4))
assert j*sigma==sigma*j and (j*sigma)**4==sigma and (j*sigma)**12==I
compiler_powers = [sum(v!=0 for v in differences((j*sigma)**k)) for k in range(1,13)]
same_reflections = [b for b in roots if glue(b)==2 and differences(I-b*b.T)==signature]
assert len(same_reflections)==2
beta = I[:,3]-I[:,5]
other_beta = I[:,3]+I[:,5]
s = I-beta*beta.T
g = sigma*s
assert beta in same_reflections and all(d==0 for d in differences(g))
assert all((M*q).dot(b)==0 for b in same_reflections) and sigma*M*q==M*q
clock_y = Counter(str(hyper.dot(sigma*r-r)) for r,d in zip(roots,signature,strict=True) if d)
reflection_y = Counter(str(hyper.dot(s*r-r)) for r,d in zip(roots,signature,strict=True) if d)

# Classify nontrivial order-two torus characters on the E8 root lattice.
# Weyl action generated by the eight integral simple reflections.
simple = sp.Matrix.hstack(sp.Matrix([1,-1,-1,-1,-1,-1,-1,1])/2,
                          I[:,0]+I[:,1], *[I[:,i+1]-I[:,i] for i in range(6)])
assert abs(simple.det())==1
root_bits = []
simple_inverse = simple.inv()
for r in roots:
    coeff = simple_inverse*r
    assert all(c.is_Integer for c in coeff)
    root_bits.append(sum((int(c)%2)<<i for i,c in enumerate(coeff)))
gram = simple.T*simple
flip_bits = [sum((int(gram[i,j])%2)<<j for j in range(8)) for i in range(8)]
todo = set(range(1,256))
orbits = []
while todo:
    start = todo.pop()
    orbit, pending = {start}, [start]
    while pending:
        x = pending.pop()
        for i,flip in enumerate(flip_bits):
            y = x^flip if (x>>i)&1 else x
            if y not in orbit:
                orbit.add(y)
                pending.append(y)
                todo.remove(y)
    negative = {sum((x&r).bit_count()%2 for r in root_bits) for x in orbit}
    assert len(negative)==1
    orbits.append({"orbit_size":len(orbit),"negative_roots":negative.pop()})
assert sorted((x["orbit_size"],x["negative_roots"]) for x in orbits)==[(120,112),(135,128)]
root_pairings = Counter(int(beta.dot(r)) for r in roots)
assert root_pairings == Counter({-2:1,-1:56,0:126,1:56,2:1})

# On the charge-0 and charge-q Heisenberg packets the root lift is the
# orthogonal Weyl action on oscillators and trivial on the charge primaries.
# Its square acts identically here because beta.q=0.
f,norms = m.code()
normalization = sp.diag(*[1/sp.sqrt(n) for n in norms])
basis = sp.Matrix.hstack(V,q)
inner_q = parent["inner_q"]
read = parent["inner"]
word_map = parent["input_word_map"]


def matrix(words, rotated=False):
    return cl(normalization * sp.Matrix(5,5,lambda i,j:read(words[i],words[j],rotated)) * normalization)


def rotated_gram(words, root_op):
    metric = cl(basis.H*M.T*root_op*M*basis)
    parent["contractions"].cache_clear()
    inner_q[1] = [[Q.from_sympy(metric[i,j]) for j in range(5)] for i in range(5)]
    return matrix(words, True)


packets = {}
for alpha in (sp.Rational(1,4),sp.Rational(3,4)):
    delta = sp.Matrix([(j+alpha)/8-sp.Rational(1,2) for j in range(8)])
    b = [Q.from_sympy(x) for x in cl(V.T*delta)]
    prep = [parent["series_response"](x,b,4) for x in f]
    outputs = [parent["vertex_zero"](x) for x in prep]
    full = matrix(outputs)
    values = {}
    for name, root_op in (("e4_minus_e6", s), ("e4_plus_e6",I-other_beta*other_beta.T)):
        signed = rotated_gram(outputs, root_op)
        assert signed.is_hermitian
        plus,minus = (cl((full+sign*signed)/2) for sign in (1,-1))
        values[name] = {"return_ranks_plus_minus":[plus.rank(),minus.rank()],
                        "removed_packets_plus":[i for i in range(5) if plus[i,i]==0],
                        "removed_packets_minus":[i for i in range(5) if minus[i,i]==0],
                        "first_packet_plus_fraction":str(sp.simplify(plus[0,0]/full[0,0]))}
    packets[str(alpha)] = values

print(json.dumps({
    "native_clock_change_counts":powers,"full_J_sigma_change_counts":compiler_powers,
    "single_reflection_repeated_counts":[112,0,112],
    "glue_matching_reflection_roots":[list(map(str,b)) for b in same_reflections],
    "native_clock_is_class_preserving_times_reflection":True,
    "hypercharge_shifts_on_changed_roots":{"clock":dict(clock_y),"one_reflection":dict(reflection_y)},
    "pairings":dict(root_pairings),"nontrivial_two_torsion_orbits":orbits,
    "root_lift_square_is_plus_on_q_and_vacuum_primaries":True,
    "full_packet_reflection":packets,
    "scope":"Actual E8 compiler roots and actual five packets in the supplied E8 parent. Root lift is not an assignment of original Q_Theta."
}, indent=2))
