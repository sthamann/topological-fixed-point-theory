"""Test the attached DET16 occupancy, Yukawa, and time-instrument conjectures."""
from collections import Counter, defaultdict
from itertools import combinations, permutations
import json
from pathlib import Path
import sys

import numpy as np
import sympy as sp

repo = Path(sys.argv[1]).resolve()
sys.path.insert(0, str(repo / "verification"))
import v1002_spin10_mirror_projector as native

gen, pair = native.positive_weyl_generators()
weights = np.array([2 * np.diag(gen[pair.index((2*j, 2*j+1))]).real
                    for j in range(5)], dtype=int).T
bits = (weights + 1) // 2
labels = (bits @ 2**np.arange(4, -1, -1)).tolist()
loc = {label: i for i, label in enumerate(labels)}
states = np.arange(1 << 16)
occupied = (states[:, None] >> np.arange(16)) & 1
q_z = (bits @ [-2,-2,-2,3,3]) % 6
q_g = (bits @ [1,1,1,1,0]) % 2
q_c = (bits @ [2,2,2,1,1]) % 4
common = (occupied @ q_z) % 6 == 0
split = common & ((occupied @ q_g) % 2 == 0)
central = common & ((occupied @ q_c) % 4 == 0)
union = split | central
assert tuple(np.count_nonzero(x) for x in (split, central, split & central, union)) == (5464,5464,3072,7856)

selected = states[union]
omissions = {
    (i,j) for i,j in combinations(range(16),2)
    if len(np.unique(selected & ~((1 << i) | (1 << j)))) == len(selected)
}
expected = {(i,j) for i,j in combinations(range(16),2)
            if q_z[i] != 0 and q_z[j] != 0 and q_z[i] != q_z[j]}
assert omissions == expected and len(omissions) == 60
# Replay maximality on the same support. A larger omission would include a triple.
assert all(len(np.unique(selected & ~(sum(1 << i for i in trio)))) < len(selected)
           for trio in combinations(range(16),3))


def labeled(pairs):
    return [[labels[i],labels[j]] for i,j in sorted(pairs)]


def exact_mask_action(p):
    transported = occupied @ (1 << np.array(p))
    return all(np.array_equal(mask, mask[transported]) for mask in (split, central))


def orbit_rows(generators):
    assert all(exact_mask_action(p) for p in generators)
    remains = set(omissions)
    orbits = []
    while remains:
        seed = min(remains)
        orbit = {seed}
        frontier = [seed]
        while frontier:
            i,j = frontier.pop()
            for p in generators:
                other = tuple(sorted((p[i],p[j])))
                if other not in orbit:
                    orbit.add(other)
                    frontier.append(other)
        assert orbit <= remains
        remains -= orbit
        orbits.append({"example_omitted_wedges":[labels[i] for i in seed],
                       "size":len(orbit), "orbit":labeled(orbit)})
    return orbits


def carrier_perm(p):
    return [loc[sum(1 << (4-p[j]) for j in range(5) if label >> (4-j) & 1)]
            for label in labels]


physical = [carrier_perm(p + q) for p in permutations(range(3))
            for q in permutations(range(3,5))]
physical_orbits = orbit_rows(physical)
assert sorted(o["size"] for o in physical_orbits) == [6]*6+[12]*2

# The union pair table determines allowable permutation cells before examining
# the charge data. This gives an upper bound on all monomial occupation symmetries.
pair_table = occupied[union].T @ occupied[union]
cells = defaultdict(list)
for i in range(16):
    cells[tuple(sorted(pair_table[i].tolist()))].append(i)
assert sorted([[labels[i] for i in cell] for cell in cells.values()]) == sorted([
    [0],[3],[5,6,9,10,17,18],[12,20,24],[15,23,27],[29,30]
])
assert all(len(set(q_z[cell])) == len(set(q_c[cell])) == 1 for cell in cells.values())

# For a permutation inside these cells, z and c stay fixed. The split predicate
# on common and not-central can only change via the binary linear difference g.
# The exact GF(2) rank shows its annihilator is generated by z mod 2.
basis = {}
for word in states[common & ~central]:
    value = int(word)
    while value:
        bit = value.bit_length()-1
        if bit not in basis:
            basis[bit] = value
            break
        value ^= basis[bit]
assert len(basis) == 15
parity_z = q_z % 2
assert not np.any((occupied[common & ~central] @ parity_z) % 2)

charge_classes = defaultdict(list)
for i,row in enumerate(zip(q_z,q_g,q_c)):
    charge_classes[tuple(row)].append(i)
fixed_generators = []
for group in charge_classes.values():
    for i,j in zip(group,group[1:]):
        p = list(range(16))
        p[i],p[j] = j,i
        fixed_generators.append(p)
label_fixed_orbits = orbit_rows(fixed_generators)
weak_swap = carrier_perm((0,1,2,4,3))
assert np.array_equal(q_g[weak_swap], q_g ^ parity_z)
monomial_orbits = orbit_rows(fixed_generators+[weak_swap])
assert sorted(o["size"] for o in monomial_orbits) == [6]*4+[18]*2

# Even a general unitary preserving union/H and intertwining exactly the
# retained 14 binary effects cannot merge these six orbits. All signatures
# are trace invariants, also under the simultaneous output complement.
projected_pair_signatures = {}
assert np.array_equal(union,union[::-1])
assert np.all(np.diag(pair_table) == np.count_nonzero(union)//2)
for omission in omissions:
    kept = [i for i in range(16) if i not in omission]
    signature = tuple(sorted(int(pair_table[i,j]) for i,j in combinations(kept,2)))
    projected_pair_signatures.setdefault(signature,set()).add(omission)
assert {frozenset(v) for v in projected_pair_signatures.values()} == {
    frozenset(tuple(loc[m] for m in pair) for pair in orbit["orbit"])
    for orbit in monomial_orbits
}

# Independently compare all 120 density contrasts to the five-slot top wedge.
difference = central.astype(int) - split.astype(int)
contrasts = occupied.T @ (difference[:,None] * occupied)
separators = {(i,j) for i,j in combinations(range(16),2) if contrasts[i,j]}
top_wedge = {(i,j) for i,j in combinations(range(16),2)
             if labels[i].bit_count() == labels[j].bit_count() == 2
             and labels[i] & labels[j] == 0}
intersection = separators & top_wedge
assert (len(separators),len(top_wedge),len(intersection)) == (14,15,3)
assert labeled(intersection) == [[3,12],[3,20],[3,24]]
assert all(contrasts[i,j] == 156 for i,j in intersection)
assert all(labels[i] == 3 for i,j in separators)
weak_higgs_wedge = {(i,j) for i,j in top_wedge if (31 ^ (labels[i] | labels[j])) & 3}
assert len(weak_higgs_wedge) == 6
assert not (weak_higgs_wedge & separators)
assert all((31 ^ (labels[i] | labels[j])) & 28 for i,j in intersection)

# Each candidate fixes the e-conjugate occupation from the same remaining
# 15 bits. The resulting nonlinear basis map preserves flat time, while a
# carrier/CAR relabeling could not exchange the candidates' degree histograms.
electron = loc[3]
others = occupied.copy()
others[:,electron] = 0
g_others = (others @ q_g) % 2
c_others = (others @ q_c) % 4
assert not np.any(c_others[common] % 2)
assert np.array_equal(split, common & (occupied[:,electron] == g_others))
assert np.array_equal(central, common & (occupied[:,electron] == c_others//2))
flip = common & (g_others != c_others//2)
transported = states ^ (flip.astype(int) << electron)
assert np.array_equal(transported[transported], states)
assert np.array_equal(central[transported], split)
assert np.array_equal(transported[[0,-1]], states[[0,-1]])
assert np.array_equal(transported & ~(1 << electron), states & ~(1 << electron))
assert np.array_equal(flip, split ^ central)

# Phase removal is diagonal, so it leaves every occupation mark unchanged.
I = sp.eye(2)
X = sp.Matrix([[0,1],[1,0]])
Y = sp.Matrix([[0,-sp.I],[sp.I,0]])
Z = sp.diag(1,-1)
Pplus = (I+X)/2
Pminus = (I-X)/2
H = I-X
t = sp.symbols("t", real=True)
U = Pplus+sp.exp(-2*sp.I*t)*Pminus
assert U.subs(t,sp.pi/2) == X
assert sp.simplify((I+U.subs(t,sp.pi/2))/2-Pplus) == sp.zeros(2)
assert H*Pplus == sp.zeros(2) and H*Pminus == 2*Pminus
for B in (I,Y,Z):
    assert sp.trace(X*B) == 0
    for Pz in ((I+Z)/2,(I-Z)/2):
        assert sp.trace(X*Pz*B*Pz) == 0
    assert sp.simplify(sp.trace(X*U.H*B*U)) == 0
assert sp.simplify(U.H*Z*U).subs(t,sp.pi/4) == -Y
b = sp.symbols("b", positive=True)
positive_filter_effect = Pplus+b*Pminus
assert sp.trace(X*positive_filter_effect) == 1-b

