#!/usr/bin/env python3
"""Exact finite check of what the marked CP map does and does not select."""
import importlib.util
import json
from pathlib import Path

import sympy as s

ROOT = Path('/Users/stefanhamann/Projekte/tfpt-theoryv4')


def load(name, path):
    spec = importlib.util.spec_from_file_location(name, path)
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def ad(u):
    return s.kronecker_product(u.conjugate(), u)


def main():
    bridge = load('bridge', ROOT / 'experiments/theory-contracts/compiler-clifford-bridge/checker.py')
    src, _ = bridge.inherited(ROOT)
    finite = bridge.finite_data(src)
    words = {v: bridge.monomial(v, bridge.generators()) for v in src.W16}
    zero = (0, 0, 0, 0)
    o5 = [v for v in src.W16 if v != zero and finite['q'][v] == 0]
    five = [next(v for v in o5 if src.iota(v)[j] == 0) for j in range(5)]
    units = [s.eye(4)] + [words[v] for v in five]
    probs = [s.Rational(7, 12)] + [s.Rational(1, 12)] * 5
    kraus = [s.sqrt(p) * u for p, u in zip(probs, units)]

    # The four actual marked Clifford generators induce a signed 5D action.
    mark_reps = []
    permutations = []
    signs = []
    fine_covariance = True
    pvm_covariance = True
    for j in range(4):
        L = (units[j + 1] + units[j + 2]) / s.sqrt(2)
        W = s.zeros(5)
        perm, sgn = [], []
        for k, g in enumerate(units[1:]):
            h = s.simplify(L * g * L.H)
            coeffs = [s.simplify(s.trace(t.H * h) / 4) for t in units[1:]]
            nz = [m for m, c in enumerate(coeffs) if c != 0]
            assert len(nz) == 1 and coeffs[nz[0]] in (1, -1)
            m, c = nz[0], coeffs[nz[0]]
            W[m, k] = c
            perm.append(m)
            sgn.append(int(c))
            fine_covariance &= s.simplify(ad(L) * ad(g) * ad(L).inv() - ad(units[m + 1])) == s.zeros(16)
            ej = s.zeros(5); ej[k, k] = 1
            em = s.zeros(5); em[m, m] = 1
            pvm_covariance &= s.simplify(W * ej * W.H - em) == s.zeros(5)
        assert W.H * W == s.eye(5)
        mark_reps.append(W)
        permutations.append(perm)
        signs.append(sgn)

    # Exact commutant dimension of the signed 5D source action.
    xs = s.symbols('x0:25')
    X = s.Matrix(5, 5, xs)
    eqs = []
    for W in mark_reps:
        eqs.extend(list(X * W - W * X))
    A, _ = s.linear_eq_to_matrix(eqs, xs)
    commutant_dim = 25 - A.rank()
    common_sign_line = s.Matrix.vstack(*[W + s.eye(5) for W in mark_reps]).nullspace()
    assert len(common_sign_line) == 1
    sign_vector = common_sign_line[0]
    sign_vector = sign_vector / s.sqrt((sign_vector.H * sign_vector)[0])
    Psign = s.simplify(sign_vector * sign_vector.H)

    # Minimal Stinespring dimension and environment states.
    # For V|psi> = sum_a K_a|psi>|a>, sigma_E[a,b]=Tr(K_a rho K_b^*).
    rho_star = s.eye(4) / 4
    sigma_star = s.Matrix(6, 6, lambda a, b: s.simplify(s.trace(kraus[a] * rho_star * kraus[b].H)))
    psi = s.Matrix([1, 2, 3, 4]) / s.sqrt(30)
    rho_generic = psi * psi.H
    sigma_generic = s.Matrix(6, 6, lambda a, b: s.simplify(s.trace(kraus[a] * rho_generic * kraus[b].H)))
    generic_offdiag = [(a, b, str(sigma_generic[a, b])) for a in range(6) for b in range(6) if a != b and sigma_generic[a, b] != 0]

    # Three inequivalent covariant instruments have the same nonselective channel.
    fine = [p * ad(u) for p, u in zip(probs, units)]
    Phi = sum(fine, s.zeros(16))
    coarse = [fine[0], sum(fine[1:], s.zeros(16))]
    trivial = [Phi]
    coarse_covariance = all(
        s.simplify(ad((units[j + 1] + units[j + 2]) / s.sqrt(2)) * branch
                   - branch * ad((units[j + 1] + units[j + 2]) / s.sqrt(2))) == s.zeros(16)
        for j in range(4) for branch in coarse
    )
    same_channel = (sum(fine, s.zeros(16)) == sum(coarse, s.zeros(16)) == sum(trivial, s.zeros(16)))

    # Even with the same signed mark action there are other covariant Kraus
    # frames inside the degenerate five-sector.  This one is generated by a
    # nontrivial unitary in the exact commutant.
    Ucomm = s.simplify(Psign + s.I * (s.eye(5) - Psign))
    assert s.simplify(Ucomm.H * Ucomm - s.eye(5)) == s.zeros(5)
    assert all(s.simplify(Ucomm * W - W * Ucomm) == s.zeros(5) for W in mark_reps)
    rotated_units = [s.simplify(sum((Ucomm[j, k] * units[k + 1] for k in range(5)), s.zeros(4))) for j in range(5)]
    rotated_fine = [fine[0]] + [s.Rational(1, 12) * ad(u) for u in rotated_units]
    rotated_same_channel = s.simplify(sum(rotated_fine, s.zeros(16)) - Phi) == s.zeros(16)
    rotated_is_distinct = s.simplify(rotated_fine[1] - fine[1]) != s.zeros(16)
    rotated_covariance = True
    for generator, W in zip([(units[j + 1] + units[j + 2]) / s.sqrt(2) for j in range(4)], mark_reps):
        for k, u in enumerate(rotated_units):
            m = next(i for i in range(5) if W[i, k] != 0)
            rotated_covariance &= s.simplify(ad(generator) * ad(u) * ad(generator).inv() - ad(rotated_units[m])) == s.zeros(16)

    result = {
        'actual_five_labels': [list(v) for v in five],
        'choi_nonzero_eigenvalues': {'7/12': 1, '1/12': 5},
        'minimal_stinespring_dimension': 6,
        'environment_decomposition': '1+5',
        'marked_environment_generator_permutations_zero_based': permutations,
        'marked_environment_generator_signs': signs,
        'signed_mark_representation_commutant_dimension': commutant_dim,
        'signed_mark_representation_split': 'sign(1)+irreducible(4)',
        'common_sign_vector': [str(x) for x in sign_vector],
        'source_axis_pvm_is_covariant': bool(pvm_covariance),
        'fine_branch_maps_are_covariant_as_labeled_set': bool(fine_covariance),
        'fixed_state_environment_density': [[str(x) for x in row] for row in sigma_star.tolist()],
        'fixed_state_five_sector_is_scalar': sigma_star[1:, 1:] == s.eye(5) / 12,
        'generic_input_environment_offdiagonal_count': len(generic_offdiag),
        'generic_input_environment_offdiagonal_sample': generic_offdiag[:12],
        'same_nonselective_channel_for_fine_coarse_trivial_instruments': bool(same_channel),
        'coarse_two_outcome_instrument_is_mark_covariant': bool(coarse_covariance),
        'distinct_rotated_five_outcome_frame_same_channel': bool(rotated_same_channel and rotated_is_distinct),
        'distinct_rotated_frame_same_fixed_mark_covariance': bool(rotated_covariance),
        'rotated_frame_uses_original_discrete_word_rays': False,
        'fixed_state_outcome_probabilities': {
            'fine_6': [str(x) for x in probs],
            'coarse_2': ['7/12', '5/12'],
            'trivial_1': ['1'],
        },
        'interpretation_boundary': [
            'The channel fixes a rank-6 minimal dilation only up to an environment unitary.',
            'The original five marked words and signed action supply a covariant axis PVM algebraically.',
            'Neither the fixed state nor covariance says that this PVM is measured, dephased, amplified, or stored.',
            'Generic inputs retain environment coherences; a classical branch record is an extra operation.',
        ],
    }
    out = Path(__file__).with_name('exact-check.json')
    out.write_text(json.dumps(result, indent=2) + '\n')
    print(json.dumps(result, indent=2))


if __name__ == '__main__':
    main()
