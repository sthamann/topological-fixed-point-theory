def uv_rg_contract():
    # For 0<m<=K(s,t), ν nonzero finite, and 0<∫ψdν<∞, density
    # Tν(t)>=m*νtotal/∫ψdν>0 on [0,∞), so ∫Tν=∞.
    m,v,d=sp.symbols("m v d",positive=True)
    require(sp.integrate(m*v/d,(sp.Symbol("t"),0,sp.oo))==sp.oo,
            "uniform positive unbounded-domain RG suddenly finite")
    ratio=sp.symbols("r",positive=True)
    update=(2*ratio+1)/(ratio+2)
    actual=sp.simplify((ratio/update)*sp.diff(update,ratio)).subs(ratio,1)
    claimed=3-2*sp.sqrt(2)  # tanh(log(M/m)/4) with M/m=2
    require(actual==sp.Rational(1,3) and sp.simplify(actual-claimed)>0,
            "published Birkhoff bound not falsified by [[2,1],[1,2]]")
    # Ordinary kernel positivity does not preserve Einstein/Higgs/R²
    # moment conditions. Even correct mass-normalizing ψ cannot do so.
    mat=sp.Matrix([[3,1],[1,1]])
    nu=sp.Matrix([sp.Rational(1,2),sp.Rational(1,2)])
    psi=sp.Matrix([sum(mat[:,i]) for i in range(2)])
    dst=mat*nu/(psi.T*nu)[0]
    require(dst==sp.Matrix([sp.Rational(2,3),sp.Rational(1,3)]),
            "mass-normalized Markov positivity preserved prescribed first moment")
    return {
      "status":"EXACT_ORIGINAL_UV_FIXED_POINT_ASSUMPTIONS_REFUTED",
      "original_uniform_kernel_lower_bound":"0<m<=K(s,t) on all [0,infinity)^2",
      "domain_of_RG":"finite positive measures on unbounded [0,infinity)",
      "total_mass_T_nu":"infinity for every nonzero finite nu with finite positive denominator",
      "unique_finite_fixed_measure_derived_from_as_stated_assumptions":False,
      "published_diameter_bound":"log(M/m) (fails for general positive kernel)",
      "actual_valid_uniform_diameter_bound":"2*log(M/m)",
      "exact_2by2_kernel":[[2,1],[1,2]],
      "actual_projective_contraction":"1/3",
      "published_claimed_upper_contraction":"3-2*sqrt(2)",
      "published_contraction_bound_falsified":True,
      "positive_normalized_kernel_preserves_prescribed_low_moments":False,
      "branch_moment_counterexample":"mean 1/2 changes to 1/3"
    }

def blocked_dirac_and_reflection():
    # f(s)=1/(1+s), positive completely monotone.
    def trf(D):
        return sp.trace((sp.eye(D.rows)+D*D).inv())
    fine={(x,y):trf(sp.Matrix([[x,y],[y,0]]))
          for x in range(2) for y in range(2)}
    coarse=[trf(sp.Matrix([[x]])) for x in range(2)]
    require(fine=={(0,0):2,(0,1):1,
                   (1,0):sp.Rational(3,2),(1,1):1}
            and coarse==[1,sp.Rational(1,2)],
            "compatible Dirac spectral action table changed")
    q=sp.symbols("q",positive=True) # q=exp(-1/2) strictly between 0 and 1
    pushed=(q**3+q**2)/(q**4+q**2)
    claimed=1/q
    require(sp.factor(pushed-claimed)==(q-1)/(q*(1+q*q)),
            "Dirac compression accidentally implies projective measure")
    # Reflection Θ(x,y)=(y,x). Spectral weight generated by
    # scalar D(x,y)=abs(x-y) is symmetric and pointwise positive,
    # yet OS kernel is indefinite.
