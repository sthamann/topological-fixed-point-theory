def integrable_kernel_repair():
    # K(s,t)=exp(-t)*(1+exp(-s-t)), ψ(s)=1+exp(-s)/2.
    # On probability measures, u=E[exp(-s)] obeys
    # F(u)=(1/2+u/3)/(1+u/2), with Lipschitz <=1/12.
    u=sp.symbols("u",nonnegative=True)
    F=(sp.Rational(1,2)+u/3)/(1+u/2)
    require(sp.simplify(sp.diff(F,u)-1/(12*(1+u/2)**2))==0,
            "positive kernel repair not contracting")
    root=(sp.sqrt(13)-2)/3
    require(sp.simplify(F.subs(u,root)-root)==0,
            "integrable normalized positive RG unique profile changed")
    t=sp.symbols("t",nonnegative=True)
    profile=sp.factor((1/(1+t)+root/(2+t))/(1+root/2))
    require(sp.simplify(profile.subs(t,0)-1)==0,
            "repaired Laplace fixed profile not probability normalized")
