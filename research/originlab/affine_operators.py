def lattice_frame():
    """A basis of the E8 lattice that contains the marked gamma and p2."""
    marked = (MARKED_GAMMA, MARKED_P2)
    found = completion_search(marked, ROOTS)
    require(found["reaches_e8"] and found.get("minimal_extra_currents") == 6,
            "six further currents must complete the marked plane")
    frame = (*marked, *(tuple(r) for r in found["witness"]))
    require(rank(frame) == 8, "completion must be a lattice basis")
    return frame, found


@lru_cache(maxsize=None)
def coordinates(frame, vector):
    """Exact coordinates of a doubled D8 vector in the frame."""
    rows = [[Fraction(frame[j][i]) for j in range(8)]+[Fraction(vector[i])] for i in range(8)]
    for column in range(8):
        pivot = next(i for i in range(column, 8) if rows[i][column])
        rows[column], rows[pivot] = rows[pivot], rows[column]
        rows[column] = [x/rows[column][column] for x in rows[column]]
        for i in range(8):
            if i != column and rows[i][column]:
                factor = rows[i][column]
                rows[i] = [x-factor*y for x, y in zip(rows[i], rows[column])]
    return tuple(row[8] for row in rows)


def integral(frame, root):
    values = coordinates(frame, root)
    require(all(v.denominator == 1 for v in values), "root must be integral in the lattice frame")
    return tuple(int(v) for v in values)


def current_algebra(fock, frame, roots, modes, states):
    """Check the level-one affine relations on explicit vectors. Returns the number of checks."""
    coords = {r: integral(frame, r) for r in roots}
    checks = 0
    for a, b in product(roots, repeat=2):
        pairing = dot(a, b)
        for m, n in product(modes, repeat=2):
            for state in states:
                left = fock.vertex(coords[a], m, fock.vertex(coords[b], n, state))
                right = fock.vertex(coords[b], n, fock.vertex(coords[a], m, state))
                commutator = fock.combine((1, left), (-1, right))
                if pairing >= 0:
                    expected = {}
                elif pairing == -1:
                    total = integral(frame, add(a, b))
                    expected = fock.combine((fock.sign(coords[a], coords[b]), fock.vertex(total, m+n, state)))
                else:
                    sign = fock.sign(coords[a], coords[b])
                    expected = fock.combine((sign, fock.heisenberg(coords[a], m+n, state)),
                                            (sign*m if m+n == 0 else 0, state))
                if commutator != expected:
                    return None
                checks += 1
    return checks


def marked_word(fock, frame, size):
    """Mode matrix elements of J^(-p1) J^gamma J^p2 on the vacuum."""
    p1, p2, gamma = (integral(frame, r) for r in (MARKED_P1, MARKED_P2, MARKED_GAMMA))
    minus_p1 = tuple(-x for x in p1)
    table = {}
    for m, n in product(range(1, size+1), repeat=2):
        state = fock.vertex(p2, -n, fock.vacuum())
        state = fock.vertex(gamma, n-m, state)
        state = fock.vertex(minus_p1, m, state)
        table[m, n] = state.get(((0,)*8, ()), Fraction(0))
    return table


def prepared_word(fock, frame, left, right, size):
    """<h_left(1) J^(-p1)_(m-1) J^gamma_(n-m) J^p2_(1-n) h_right(-1)> on the vacuum."""
    p1, p2, gamma = (integral(frame, r) for r in (MARKED_P1, MARKED_P2, MARKED_GAMMA))
    minus_p1 = tuple(-x for x in p1)
    left, right = coordinates(frame, left), coordinates(frame, right)
    table = {}
    for m, n in product(range(1, size+1), repeat=2):
        state = fock.heisenberg(right, -1, fock.vacuum())
        state = fock.vertex(p2, 1-n, state)
        state = fock.vertex(gamma, n-m, state)
        state = fock.vertex(minus_p1, m-1, state)
        state = fock.heisenberg(left, 1, state)
        table[m, n] = state.get(((0,)*8, ()), Fraction(0))
    return table


def ward_coefficients(left, right, size):
    """Coefficients of x^m y^n in the closed Ward form of affine_polarization, over Q(i).

    Values are pairs (real, imaginary). The closed form is
    W(x,y) [ <l,r> - (sum_k <l,a_k> z_k)(sum_j <r,a_j>/z_j) ] at
    z = (1, i x, -x y), with W = -sum i^(m+n-2) min(m,n) x^m y^n.
    """
    legs = (neg(MARKED_P1), MARKED_GAMMA, MARKED_P2)

    def pairing(a, b):
        return Fraction(sum(x*y for x, y in zip(a, b)), 4)

    powers = ((0, 0), (1, 0), (1, 1))                 # exponents of x and y in z_k
    phases = ((1, 0), (0, 1), (-1, 0))                 # 1, i, -1 as (re, im)

    def times(a, b):
        return (a[0]*b[0]-a[1]*b[1], a[0]*b[1]+a[1]*b[0])

    def inverse(a):
        return (a[0], -a[1])                           # unit phases only

    factor = {(0, 0): (pairing(left, right), Fraction(0))}
    for k in range(3):
        for j in range(3):
            weight = -pairing(left, legs[k])*pairing(right, legs[j])
            phase = times(phases[k], inverse(phases[j]))
            key = (powers[k][0]-powers[j][0], powers[k][1]-powers[j][1])
            old = factor.get(key, (Fraction(0), Fraction(0)))
            factor[key] = (old[0]+weight*phase[0], old[1]+weight*phase[1])
    unit = ((1, 0), (0, 1), (-1, 0), (0, -1))
    out = {}
    for m, n in product(range(-1, size+3), repeat=2):
        total = (Fraction(0), Fraction(0))
        for (dx, dy), value in factor.items():
            a, b = m-dx, n-dy
            if a >= 1 and b >= 1:
                bare = times((-min(a, b), 0), unit[(a+b-2) % 4])
                term = times(bare, value)
                total = (total[0]+term[0], total[1]+term[1])
        out[m, n] = total
    return out


def return_matrix(fock, frame, root, degree):
    """Matrix of F E on the neutral grade in the monomial basis, E = E_{root,-1}, F = E*."""
    alpha = integral(frame, root)
    minus = tuple(-x for x in alpha)
    basis = fock.basis((0,)*8, degree)
    index = {next(iter(b)): i for i, b in enumerate(basis)}
    columns = []
    for b in basis:
        # E_{alpha,-1}* = -E_{-alpha,1} in this cocycle convention, checked in controls().
        image = fock.vertex(minus, 1, fock.vertex(alpha, -1, b))
        column = [Fraction(0)]*len(basis)
        for key, value in image.items():
            column[index[key]] = -value
        columns.append(column)
    return [[columns[j][i] for j in range(len(basis))] for i in range(len(basis))]


def multiply(a, b):
    size = len(a)
    rows = [[(k, x) for k, x in enumerate(row) if x] for row in b]
    out = [[Fraction(0)]*size for _ in range(size)]
    for i, row in enumerate(a):
        target = out[i]
        for k, x in enumerate(row):
            if x:
                for j, y in rows[k]:
                    target[j] += x*y
    return out


def shifted(matrix, value):
    return [[x-(value if i == j else 0) for j, x in enumerate(row)] for i, row in enumerate(matrix)]


def spectrum(matrix, values):
    found = {}
    for value in values:
        kernel = len(matrix)-rank(shifted(matrix, value))
        if kernel:
            found[value] = kernel
    return found


def joint_return(fock, frame):
    """Neutral grade-two returns of the marked A2 and of eight mutually orthogonal roots."""
    def pair_root(i, j, sign):
        row = [0]*8
        row[i], row[j] = 2, 2*sign
        return tuple(row)

    orthogonal = [pair_root(i, j, sign) for i, j in ((0, 5), (1, 2), (3, 4), (6, 7)) for sign in (1, -1)]
    require(orthogonal[0] == MARKED_GAMMA and
            all(dot(a, b) == 0 for i, a in enumerate(orthogonal) for b in orthogonal[i+1:]),
            "orthogonal frame through the marked middle root changed")
    roots = [*orthogonal, MARKED_P1, MARKED_P2]
    returns = {r: return_matrix(fock, frame, r, 2) for r in roots}
    size = len(returns[MARKED_GAMMA])
    require(all(spectrum(m, (1, 4, 9)) == {1: size-1, 4: 1} for m in returns.values()),
            "each root return on neutral grade two must be 1 plus a rank-one excess of 3")

    def commutator_rank(a, b):
        # The identity parts cancel, so the sparse rank-one excesses suffice.
        ab, ba = multiply(excess[a], excess[b]), multiply(excess[b], excess[a])
        return rank([[x-y for x, y in zip(r, s)] for r, s in zip(ab, ba)])

    excess = {r: shifted(m, 1) for r, m in returns.items()}

    def excess_rank(family):
        return rank([[sum(excess[r][i][j] for r in family) for j in range(size)] for i in range(size)])

    require(all(commutator_rank(a, b) == 0 for i, a in enumerate(orthogonal) for b in orthogonal[i+1:]),
            "returns of orthogonal roots must commute")
    marked = (MARKED_GAMMA, MARKED_P1, MARKED_P2)
    names = {MARKED_GAMMA: "gamma", MARKED_P1: "p1", MARKED_P2: "p2"}
    marked_commutators = [{"roots": [names[a], names[b]], "pairing": dot(a, b),
                           "commutator_rank": commutator_rank(a, b)}
                          for i, a in enumerate(marked) for b in marked[i+1:]]
    require(all((row["commutator_rank"] == 0) == (row["pairing"] <= 0) for row in marked_commutators),
            "grade-two returns must commute exactly for root pairings 0 and -1")
    return {"neutral_grade": 2, "dimension": size,
            "single_root_spectrum": {"1": size-1, "4": 1},
            "orthogonal_frame_doubled": [list(r) for r in orthogonal],
            "orthogonal_frame_commutes": True,
            "orthogonal_frame_excess_rank": excess_rank(orthogonal),
            "marked_plane_excess_rank": excess_rank(marked),
            "marked_plane_commutators": marked_commutators}


DOUBLET_ALPHA = (0, 0, 0, 2, 0, -2, 0, 0)          # e4 - e6, weak doublet, Y = 1/2
DOUBLET_DELTA = add(MARKED_GAMMA, DOUBLET_ALPHA)   # e1 + e4, colour triplet weak doublet, Y = 1/6


def simple_roots(system):
    """Simple roots of a closed root system for one generic height function."""
    height = (1009, 811, 613, 419, 211, 103, 41, 7)
    positive = [r for r in system if sum(x*y for x, y in zip(r, height)) > 0]
    require(2*len(positive) == len(system), "height function must be generic")
    sums = {add(a, b) for a in positive for b in positive}
    return sorted(r for r in positive if r not in sums)


def determinant(matrix):
    rows = [[Fraction(x) for x in row] for row in matrix]
    value = Fraction(1)
    for column in range(len(rows)):
        pivot = next((i for i in range(column, len(rows)) if rows[i][column]), None)
        if pivot is None:
            return Fraction(0)
        if pivot != column:
            rows[column], rows[pivot] = rows[pivot], rows[column]
            value = -value
        value *= rows[column][column]
        for i in range(column+1, len(rows)):
            factor = rows[i][column]/rows[column][column]
            if factor:
                rows[i] = [x-factor*y for x, y in zip(rows[i], rows[column])]
    return value


def unit(index):
    return tuple(2 if i == index else 0 for i in range(8))


def weak_casimir(fock, frame, vector):
    """Quadratic Casimir of the zero modes of the weak slot root, spin j gives j(j+1)."""
    beta = integral(frame, WEAK_ROOT)
    minus = tuple(-x for x in beta)
    orientation = fock.sign(beta, minus)              # [E_beta,0 , E_-beta,0] = orientation * H_beta,0
    cartan = fock.heisenberg(beta, 0, fock.heisenberg(beta, 0, vector))
    up_down = fock.vertex(beta, 0, fock.vertex(minus, 0, vector))
    down_up = fock.vertex(minus, 0, fock.vertex(beta, 0, vector))
    return fock.combine((Fraction(1, 4), cartan), (Fraction(orientation, 2), up_down),
                        (Fraction(orientation, 2), down_up))


def doublet_extension(fock, frame, word_size):
    """Weak doublet sector: algebra, lattice and operator checks of the neutral doublet word."""
    even = frozenset(r for r in ROOTS if dot(r, WEAK_ROOT) % 2 == 0)
    odd = sorted(ROOT_SET-even)
    weights = {w: sum(1 for r in ROOTS if dot(r, WEAK_ROOT) == w) for w in (-2, -1, 0, 1, 2)}
    require(weights == {-2: 1, -1: 56, 0: 126, 1: 56, 2: 1}, "weak weight census changed")
    require(all(len(closure(even | {r})) == 240 for r in odd),
            "every single weak doublet current must complete the even algebra to E8")

    # Lattice of the even currents: index two, and the split of the conformal weight.
    basis = simple_roots(even)
    index_square = determinant([[dot(a, b) for b in basis] for a in basis])
    require(len(basis) == 8 and index_square == 4, "even currents must span an index-two sublattice")
    require(all(abs(dot(r, WEAK_ROOT)) == 1 for r in odd), "odd currents must have weak weight one half")
    weak_weight = Fraction(1, 2)*Fraction(1, 2)       # |projection on the weak root|^2 / 2
    require(weak_weight == Fraction(1, 4) and 1-weak_weight == Fraction(3, 4), "conformal weight split changed")

    # Charges of the doublet triangle and the generated ladder.
    signatures = {name: signature_row(root) for name, root in
                  (("gamma", MARKED_GAMMA), ("alpha", DOUBLET_ALPHA), ("delta", DOUBLET_DELTA))}
    require([(row["colour_triality"], row["hypercharge"], row["glue_class"]) for row in signatures.values()]
            == [(1, "-1/3", 2), (0, "1/2", 2), (1, "1/6", 0)] and dot(MARKED_GAMMA, DOUBLET_ALPHA) == -1
            and DOUBLET_DELTA in ROOT_SET, "doublet triangle charges changed")
    e = [unit(i) for i in range(8)]
    steps = (("marked", (MARKED_P1, MARKED_P2)),
             ("colour and weak roots", (add(e[0], neg(e[1])), add(e[1], neg(e[2])), WEAK_ROOT)),
             ("weak doublet e4-e6", (DOUBLET_ALPHA,)),
             ("internal e6-e7", (add(e[5], neg(e[6])),)),
             ("internal e7-e8", (add(e[6], neg(e[7])),)))
    seeds, ladder = [], []
    for name, extra in steps:
        seeds.extend(extra)
        system = closure(seeds)
        ladder.append({"added": name, "system": components(system), "roots": len(system),
                       "dimension": len(system)+rank(sorted(system))})
    require([row["system"] for row in ladder] == [["A2"], ["A1", "A4"], ["E6"], ["E7"], ["E8"]]
            and determinant([[dot(a, b) for b in seeds] for a in seeds]) == 1,
            "the eight ladder roots must be a lattice basis passing through E6 and E7")
    without_doublet = closure([r for r in seeds if r != DOUBLET_ALPHA])
    require(components(without_doublet) == ["A1", "E6"], "ladder without the doublet must stay proper")

    # Operator checks.
    gamma, alpha, delta, p2 = (integral(frame, r) for r in (MARKED_GAMMA, DOUBLET_ALPHA, DOUBLET_DELTA, MARKED_P2))
    minus_delta = tuple(-x for x in delta)
    zero = ((0,)*8, ())
    word, casimir_word = {}, {}
    for m, n in product(range(1, word_size+1), repeat=2):
        first = fock.vertex(alpha, -n, fock.vacuum())
        tail = lambda state: fock.vertex(minus_delta, m, fock.vertex(gamma, n-m, state)).get(zero, Fraction(0))
        word[m, n] = tail(first)
        casimir_word[m, n] = tail(weak_casimir(fock, frame, first))
    orientation = word[1, 1]
    require(orientation in (1, -1) and all(orientation*value == min(m, n) for (m, n), value in word.items()),
            "the neutral doublet word must have the same min(m,n) kernel")
    require(all(casimir_word[key] == Fraction(3, 4)*word[key] for key in word),
            "the weak Casimir must act as 3/4 inside the doublet word")
    for n in range(1, 5):
        singlet = fock.vertex(p2, -n, fock.vacuum())
        doublet = fock.vertex(alpha, -n, fock.vacuum())
        require(weak_casimir(fock, frame, singlet) == {} and
                weak_casimir(fock, frame, doublet) == fock.combine((Fraction(3, 4), doublet)),
                "weak Casimir values 0 and 3/4 failed on the first charged vectors")
    lower = integral(frame, add(DOUBLET_ALPHA, neg(WEAK_ROOT)))
    partner = fock.vertex(tuple(-x for x in integral(frame, WEAK_ROOT)), 0, fock.vertex(alpha, -1, fock.vacuum()))
    target = fock.vertex(lower, -1, fock.vacuum())
    require(partner in (target, fock.combine((-1, target))), "weak lowering must reach the partner current")

    # The six intermediate paths to each quark doublet weight end on one line.
    path_counts = []
    for colour, weak in product(range(3), (3, 4)):
        goal = add(e[colour], e[weak])
        vectors, excited = [], []
        for r in ROOTS:
            rest = add(goal, neg(r))
            if (rest in ROOT_SET and charge_signature(r)[1:] == (1, Fraction(-1, 3)) and dot(r, WEAK_ROOT) == 0
                    and charge_signature(rest)[1:] == (0, Fraction(1, 2)) and abs(dot(rest, WEAK_ROOT)) == 1):
                vectors.append(fock.vertex(integral(frame, r), 0,
                                           fock.vertex(integral(frame, rest), -1, fock.vacuum())))
                excited.append(fock.vertex(integral(frame, r), -1,
                                           fock.vertex(integral(frame, rest), -1, fock.vacuum())))
        keys = sorted({key for v in vectors for key in v})
        require(len(vectors) == 6 and rank([[v.get(key, 0) for key in keys] for v in vectors]) == 1
                and all(fock.inner(v, v) == 1 for v in vectors), "six unit paths must span one line")
        # One grade higher the paths differ by their oscillator polarization e_colour + s e_r.
        keys = sorted({key for v in excited for key in v})
        require(rank([[v.get(key, 0) for key in keys] for v in excited]) == 4 and
                sorted(fock.inner(a, b) for a in excited for b in excited).count(2) == 6,
                "grade-two paths must span the colour direction and the three family coordinates")
        path_counts.append(len(vectors))

    # Family labels in the bracket of two class-one spinor currents.
    spinors = [r for r in ROOTS if r[0] % 2 and charge_signature(r)[0] == 1]
    pairs = [(a, b) for a in spinors for b in spinors if add(a, b) in ROOT_SET]
    require(len(spinors) == 64 and pairs and all(a[5:] != b[5:] and charge_signature(add(a, b))[0] == 2
                                                  for a, b in pairs),
            "two class-one spinor currents with equal family weight must not close on a current")
    return {
        "weak_weight_census": {str(k): v for k, v in weights.items()},
        "single_odd_current_completes_even_algebra": {"tested": len(odd), "all_reach_e8": True},
        "even_sublattice_index": 2, "odd_sector_conformal_weights": {"A1": "1/4", "E7": "3/4", "sum": "1"},
        "doublet_triangle": signatures,
        "neutral_doublet_word": "J^(-delta) J^gamma J^alpha, delta = gamma + alpha",
        "neutral_doublet_word_coefficients": f"min(m,n) for m,n <= {word_size}, identical to the marked word",
        "weak_casimir": {"marked_first_vector": "0", "doublet_first_vector": "3/4",
                         "inside_doublet_word": "3/4 of the word at every tested mode pair"},
        "ladder": ladder, "ladder_gram_determinant": 1,
        "ladder_without_doublet": ["A1", "E6"],
        "quark_doublet_paths": {"weights": len(path_counts), "paths_each": 6, "span_rank_each": 1,
                                "grade_two_span_rank_each": 4,
                                "grade_two_reading": "one common direction and the three family Cartan "
                                                     "coordinates 6, 7, 8 as oscillator polarizations"},
        "spinor_bracket_family_weights": {"pairs": len(pairs), "equal_family_weight_pairs": 0},
        "scope": "Statements about the affine E8 vacuum module. Vacuum words in weak-even currents equal "
                 "those of the E7 x SU(2) level-one vacuum, so they cannot show the doublet sector there. "
                 "A physical source with its own time evolution is not covered by this blindness.",
    }


def controls(word_size=6, algebra_roots=10):
    frame, completion = lattice_frame()
    gram = [[dot(a, b) for b in frame] for a in frame]
    fock = LatticeFock(gram)
    marked = (MARKED_P1, MARKED_P2, MARKED_GAMMA)
    plane = closure(marked)
    require(components(plane) == ["A2"] and len(plane) == 6, "the marked charges must span one A2")

    # Operator relations at level one, on vacuum and first excited vectors.
    commutant = sorted(r for r in ROOTS if all(dot(r, m) == 0 for m in marked))
    require(len(commutant) == 72 and components(commutant) == ["E6"], "commutant of the marked plane changed")
    sample = [*sorted(plane), *commutant[:max(0, algebra_roots-6)]]
    sample += [neg(r) for r in sample if neg(r) not in sample]
    states = [fock.vacuum(), *fock.basis((0,)*8, 1), fock.vacuum(integral(frame, MARKED_P2)),
              fock.vacuum(integral(frame, commutant[0]))]
    relations = current_algebra(fock, frame, sample, (-1, 0, 1), states)
    require(relations is not None, "level-one current relations failed on the explicit operators")
    untwisted = current_algebra(LatticeFock(gram, trivial_cocycle=True), frame, sorted(plane), (-1, 0, 1),
                                [fock.vacuum()])
    require(untwisted is None, "dropping the cocycle must break the current algebra")

    # Adjoint and level from the explicit form.
    gamma = integral(frame, MARKED_GAMMA)
    minus_gamma = tuple(-x for x in gamma)
