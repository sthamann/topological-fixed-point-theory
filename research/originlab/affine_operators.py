"""Operator-level level-one E8 source and a class-constrained mark completion search.

The earlier affine controls use closed three-point kernels. This module
builds the actual mode operators of the Frenkel-Kac lattice construction on
the E8 root lattice and applies them to exact Fock vectors. Its currents
change the charge sector and are not quadratic in free fermion modes.
Every check below uses those operators directly.

Scope. Everything here is a statement about the given affine E8 vacuum
module at level one in the fixed physical D8 chart. It carries no weighted
R113 value and proves no physical source identity.
"""
from collections import deque
from fractions import Fraction
from functools import lru_cache
from itertools import product

MARKED_P1 = (1, 1, 1, 1, 1, 1, 1, 1)          # doubled D8 coordinates
MARKED_P2 = (-1, 1, 1, 1, 1, -1, 1, 1)
MARKED_GAMMA = tuple(a-b for a, b in zip(MARKED_P1, MARKED_P2))


def require(condition, message):
    if not condition:
        raise ArithmeticError(message)


# ---------------------------------------------------------------- roots

def e8_roots():
    """All 240 roots of D8+ in doubled integer coordinates."""
    roots = []
    for i in range(8):
        for j in range(i+1, 8):
            for a, b in product((2, -2), repeat=2):
                row = [0]*8
                row[i], row[j] = a, b
                roots.append(tuple(row))
    roots += [signs for signs in product((1, -1), repeat=8) if signs.count(-1) % 2 == 0]
    require(len(roots) == 240 and len(set(roots)) == 240, "E8 root census changed")
    return roots


def dot(a, b):
    value = sum(x*y for x, y in zip(a, b))
    require(value % 4 == 0, "E8 lattice pairing must be integral")
    return value//4


def add(a, b):
    return tuple(x+y for x, y in zip(a, b))


def neg(a):
    return tuple(-x for x in a)


def charge_signature(root):
    """Glue class, colour triality and hypercharge, as in affine_time."""
    half = root[0]+root[1]-2*root[2]
    require(half % 2 == 0, "triality must be integral on the E8 lattice")
    hyper = Fraction(sum(x*y for x, y in zip(root, (-2, -2, -2, 3, 3, 0, 0, 0))), 12)
    return sum(root[5:]) % 4, (half//2) % 3, hyper


ROOTS = e8_roots()
ROOT_SET = frozenset(ROOTS)


def closure(seed):
    """Roots of the Lie algebra generated by the root vectors of the seed and their adjoints."""
    found = set(seed) | {neg(r) for r in seed}
    queue = deque(found)
    while queue:
        a = queue.popleft()
        for b in tuple(found):
            c = add(a, b)
            if c in ROOT_SET and c not in found:
                found.add(c)
                queue.append(c)
    return frozenset(found)


def rank(vectors):
    rows = [[Fraction(x) for x in v] for v in vectors]
    size = 0
    for column in range(len(rows[0]) if rows else 0):
        pivot = next((i for i in range(size, len(rows)) if rows[i][column]), None)
        if pivot is None:
            continue
        rows[size], rows[pivot] = rows[pivot], rows[size]
        lead = rows[size][column]
        for i in range(size+1, len(rows)):
            if rows[i][column]:
                factor = rows[i][column]/lead
                rows[i] = [x-factor*y for x, y in zip(rows[i], rows[size])]
        size += 1
    return size


def components(system):
    """Irreducible components of a closed simply laced root system, by name."""
    names = {}
    for r in range(1, 9):
        names[(r, r*(r+1))] = f"A{r}"
        if r >= 4:
            names[(r, 2*r*(r-1))] = f"D{r}"
    names.update({(6, 72): "E6", (7, 126): "E7", (8, 240): "E8"})
    left = set(system)
    found = []
    while left:
        start = left.pop()
        part, queue = {start}, deque([start])
        while queue:
            a = queue.popleft()
            linked = {b for b in left if dot(a, b)}
            left -= linked
            part |= linked
            queue.extend(linked)
        key = (rank(sorted(part)), len(part))
        require(key in names, "unrecognised root system component")
        found.append(names[key])
    return sorted(found)


CLASSES = {
    "any_root": lambda glue, triality, hyper, root: True,
    "d8_pair_currents": lambda glue, triality, hyper, root: all(x % 2 == 0 for x in root),
    "spinor_currents": lambda glue, triality, hyper, root: all(x % 2 for x in root),
    "colour_centre_neutral": lambda glue, triality, hyper, root: triality == 0,
    "glue_class_zero": lambda glue, triality, hyper, root: glue == 0,
    "centre_and_glue_neutral": lambda glue, triality, hyper, root: triality == 0 and glue == 0,
    "centre_and_hypercharge_neutral": lambda glue, triality, hyper, root: triality == 0 and hyper == 0,
    "hypercharge_neutral": lambda glue, triality, hyper, root: hyper == 0,
    "centre_neutral_d8_pairs": lambda glue, triality, hyper, root:
        triality == 0 and all(x % 2 == 0 for x in root),
}


def conserved_parities(system):
    """Roots delta whose pairing is even on the whole system and odd on every other root.

    Such a root gives a Z2 grading that every word in the generated
    currents preserves, and every missing current changes.
    """
    missing = ROOT_SET-system
    return [list(delta) for delta in sorted(system)
            if delta > neg(delta) and all(dot(delta, r) % 2 == 0 for r in system)
            and all(dot(delta, r) % 2 for r in missing)]


def completion_search(marked, allowed):
    """Fewest extra root currents from the allowed class that generate all of E8.

    Every extra current can raise the rank of the generated system by at
    most one, so 8 minus the marked rank is a lower bound. A depth first
    search over closed root systems looks for a witness that attains it.
    A class whose whole union stays in a proper subsystem is an exact
    negative result. Failed closed systems are remembered, so an
    unsuccessful search at the bound is exhaustive for the class.
    """
    start = closure(marked)
    reachable = closure(set(marked) | set(allowed))
    if len(reachable) != 240:
        return {"reaches_e8": False, "largest_generated_system": components(reachable),
                "generated_roots": len(reachable), "generated_rank": rank(sorted(reachable)),
                "conserved_parities": conserved_parities(reachable)}
    allowed = sorted(allowed)
    bound = 8-rank(sorted(start))
    failed = set()

    def search(system, basis, extra):
        if len(system) == 240:
            return extra
        if len(extra) == bound or system in failed:
            return None
        for root in allowed:
            if root in system or rank([*basis, root]) == len(basis):
                continue
            found = search(closure(system | {root}), [*basis, root], (*extra, root))
            if found is not None:
                return found
        failed.add(system)
        return None

    witness = search(start, list(marked), ())
    if witness is None:
        return {"reaches_e8": True, "attains_rank_bound": False, "rank_bound": bound,
                "closed_systems_exhausted": len(failed)}
    return {"reaches_e8": True, "attains_rank_bound": True, "minimal_extra_currents": bound,
            "witness": [list(r) for r in witness],
            "witness_signatures": [signature_row(r) for r in witness]}


def signature_row(root):
    glue, triality, hyper = charge_signature(root)
    return {"root_doubled": list(root), "glue_class": glue, "colour_triality": triality,
            "hypercharge": str(hyper)}


WEAK_ROOT = (0, 0, 0, 2, -2, 0, 0, 0)            # exchanges the two weak carrier slots


def weak_parity(marked):
    """The Z2 grading by the weak slot root that the marked plane preserves."""
    even = [r for r in ROOTS if dot(r, WEAK_ROOT) % 2 == 0]
    odd = [r for r in ROOTS if dot(r, WEAK_ROOT) % 2]
    require(all(dot(r, WEAK_ROOT) == 0 for r in marked), "marked charges must be weak singlets")
    system = closure(set(marked) | set(even))
    require(system == frozenset(even) and len(even) == 128 and components(even) == ["A1", "E7"],
            "weak singlet and triplet currents must close on A1 x E7")
    require(all(charge_signature(r)[2] != 0 for r in odd),
            "every weak doublet current must carry hypercharge")
    neutral_pairs = sorted({(charge_signature(r)[0], str(abs(charge_signature(r)[2]))) for r in odd
                            if charge_signature(r)[1] == 0 and all(x % 2 == 0 for x in r)})
    return {"weak_root_doubled": list(WEAK_ROOT), "even_roots": len(even), "odd_roots": len(odd),
            "even_system": ["A1", "E7"],
            "odd_currents_all_carry_hypercharge": True,
            "colour_neutral_pair_doublets_glue_and_abs_hypercharge": [list(row) for row in neutral_pairs]}


# ---------------------------------------------------------------- Fock space

class LatticeFock:
    """Exact vectors of the lattice vertex algebra of an even lattice with a chosen basis.

    A vector is a dict from (charge, monomial) to a Fraction. The charge
    is an integer tuple in the lattice basis. A monomial is a sorted tuple
    of creation letters (n, j) standing for basis_j(-n), n >= 1.
    """

    def __init__(self, gram, trivial_cocycle=False):
        self.gram = [list(row) for row in gram]
        self.size = len(gram)
        self.trivial_cocycle = trivial_cocycle
        require(all(self.gram[i][j] == self.gram[j][i] for i in range(self.size) for j in range(self.size))
                and all(self.gram[i][i] % 2 == 0 for i in range(self.size)), "an even lattice is required")

    def pair(self, a, b):
        return sum(x*sum(g*y for g, y in zip(row, b) if g) for x, row in zip(a, self.gram) if x)

    def sign(self, a, b):
        if self.trivial_cocycle:
            return 1
        exponent = sum(a[i]*self.gram[i][j]*b[j] for i in range(self.size) for j in range(i))
        exponent += sum(a[i]*b[i]*self.gram[i][i]//2 for i in range(self.size))
        return -1 if exponent % 2 else 1

    def vacuum(self, charge=None):
        return {(tuple(charge) if charge else (0,)*self.size, ()): Fraction(1)}

    @staticmethod
    def combine(*terms):
        out = {}
        for factor, vector in terms:
            for key, value in vector.items():
                total = out.get(key, 0)+factor*value
                if total:
                    out[key] = total
                else:
                    out.pop(key, None)
        return out

    def heisenberg(self, h, n, vector):
        """h(n) for h given by rational coordinates in the lattice basis."""
        out = {}
        if n == 0:
            for (charge, mono), value in vector.items():
                weight = self.pair(h, charge)
                if weight:
                    out[(charge, mono)] = value*weight
            return out
        if n < 0:
            for (charge, mono), value in vector.items():
                for j, c in enumerate(h):
                    if c:
                        key = (charge, tuple(sorted((*mono, (-n, j)))))
                        out[key] = out.get(key, 0)+value*c
        else:
            weights = [self.pair(h, tuple(int(i == j) for i in range(self.size))) for j in range(self.size)]
            for (charge, mono), value in vector.items():
                for position, (m, j) in enumerate(mono):
                    if m == n and weights[j]:
                        key = (charge, mono[:position]+mono[position+1:])
                        out[key] = out.get(key, 0)+value*n*weights[j]
        return {key: value for key, value in out.items() if value}

    def vertex(self, alpha, k, vector):
        """The mode E_{alpha,k} of E_alpha(z) = sum_k E_{alpha,k} z^(-k-1)."""
        alpha = tuple(alpha)
        by_charge = {}
        for (charge, mono), value in vector.items():
            by_charge.setdefault(charge, {})[(charge, mono)] = value
        out = {}
        for charge, part in by_charge.items():
            shift = self.pair(alpha, charge)
            target = tuple(a+b for a, b in zip(alpha, charge))
            degree = max(sum(n for n, _ in mono) for _, mono in part)
            lowered = [part]
            for q in range(1, degree+1):
                lowered.append(self.combine(*((Fraction(-1, q), self.heisenberg(alpha, n, lowered[q-n]))
                                              for n in range(1, q+1))))
            total = {}
            for q, state in enumerate(lowered):
                r = q-k-1-shift
                if r < 0 or not state:
                    continue
                raised = [state]
                for s in range(1, r+1):
                    raised.append(self.combine(*((Fraction(1, s), self.heisenberg(alpha, -n, raised[s-n]))
                                                 for n in range(1, s+1))))
                total = self.combine((1, total), (1, raised[r]))
            sign = self.sign(alpha, charge)
            for (_, mono), value in total.items():
                key = (target, mono)
                out[key] = out.get(key, 0)+sign*value
        return {key: value for key, value in out.items() if value}

    def inner(self, left, right):
        """Contravariant form with basis_j(-n)* = basis_j(n) and orthonormal charges."""
        total = Fraction(0)
        for (charge, mono), value in left.items():
            state = {key: v for key, v in right.items() if key[0] == charge}
            for n, j in mono:
                if not state:
                    break
                unit = tuple(int(i == j) for i in range(self.size))
                state = self.heisenberg(unit, n, state)
            total += value*state.get((charge, ()), 0)
        return total

    def basis(self, charge, degree):
        letters = [(n, j) for n in range(1, degree+1) for j in range(self.size)]

        def build(remaining, start):
            if remaining == 0:
                yield ()
                return
            for index in range(start, len(letters)):
                n = letters[index][0]
                if n <= remaining:
                    for tail in build(remaining-n, index):
                        yield (letters[index], *tail)
        return [{(tuple(charge), tuple(sorted(mono))): Fraction(1)} for mono in build(degree, 0)]


